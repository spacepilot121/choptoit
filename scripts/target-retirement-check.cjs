const fs=require('node:fs'),path=require('node:path'),vm=require('node:vm'),assert=require('node:assert/strict');
const html=fs.readFileSync(path.join(__dirname,'..','index.html'),'utf8');
let stopped=0,removedTimer=0,removedFromGroup=0,exit;
const actor=extra=>({active:true,alpha:1,destroy(){this.active=false;},...extra});
const jester=actor({startFromRight:false});
const old=actor({jester,collected:false,body:{enable:true},moveTween:{stop(){stopped++;}},yorkWaveTween:{stop(){stopped++;}},barrelPulseTween:{stop(){stopped++;}},barrelBlinkEvent:{remove(){removedTimer++;}}});
const bird=actor({targetType:'bird',collected:false,body:{enable:true}});
const group={getChildren:()=>[old,bird],remove(target){assert.equal(target,old);removedFromGroup++;}};
const scene={tweens:{killTweensOf(){},add(config){exit=config;}}};
const context={targetGroup:group,GAME_WIDTH:800};
vm.createContext(context);
vm.runInContext(html.slice(html.indexOf('function retirePreviousRoundTargets('),html.indexOf('function spawnPrisoner(')),context);
context.retirePreviousRoundTargets(scene);
assert.equal(removedFromGroup,1,'Only an unhit pole target leaves the physics group');
assert.equal(old.collected,true);assert.equal(old.body.enable,false);
assert.equal(stopped,3);assert.equal(removedTimer,1);
assert.equal(exit.x,-100);assert.equal(exit.duration,650);
assert.equal(old.active,true,'The old jester remains visible during the exit animation');
exit.onComplete();
assert.equal(old.active,false);assert.equal(jester.active,false);
assert.equal(bird.active,true,'A passing bird keeps its flight window');
assert.equal(bird.body.enable,true);
console.log('Old pole targets leave between customers without shortening bird flights or staying collidable.');
